    /// <summary>True when either table has the key.</summary>
    public static bool Has(string key)
    {
        return English.ContainsKey(key) || French.ContainsKey(key);
    }

    /// <summary>
    ///     The text of <paramref name="key" /> in <paramref name="lang" />, English when French lacks it, each
    ///     <c>{name}</c> replaced from <paramref name="values" />. A key in neither table is a defect and throws.
    /// </summary>
    public static string Get(string lang, string key, params (string Name, string Value)[] values)
    {
        var text = (lang == HubLang.Fr ? French.GetValueOrDefault(key) : null) ?? English.GetValueOrDefault(key) ??
                   throw new KeyNotFoundException("No text for " + key + ".");
        if (values.Length == 0)
            return text;
        var filled = new StringBuilder(text);
        foreach (var (name, value) in values)
            filled.Replace("{" + name + "}", value);
        return filled.ToString();
    }
